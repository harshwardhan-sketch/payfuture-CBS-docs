#!/usr/bin/env python3
"""Pull the live API specs into api-spec/.

    python3 tools/import_spec.py

Downloads the two specs the live API reference (docs.payfuturefs.com) is built from. Saves them unchanged as the
downloadable OpenAPI documents (api-spec/downloads/, JSON and YAML), applies FIXES, and writes api-spec/gateway.js and api-spec/auth.js (window.SPECS.gateway / window.SPECS.auth). The site never loads anything
from another website: run this again whenever the API changes, then run tools/check.py.
To import from saved files instead:  python3 tools/import_spec.py gateway.json auth.json
"""
import json, sys, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = {
    'gateway': 'https://secure-mtapi.payfuturefs.com/gateway/v3/api-docs/public',
    'auth': 'https://secure-mtapi.payfuturefs.com/auth/v3/api-docs',
}

# Wording and example fixes: (spec, schema, field, key, new value). None removes the key.
FIXES = [
    # "dont show dummy anywhere": the live text says a dummy value may be passed
    ('gateway', 'WalletPaymentDetails', 'documentId', 'description', "The recipient's CNIC (national identity card) number."),
]

# file names of the downloadable OpenAPI documents (api-spec/downloads/), as offered on the live API reference
DOWNLOADS = {'gateway': 'core-banking-apis', 'auth': 'account-management-apis'}

def to_yaml(v, ind=0):
    """A small YAML writer (no extra packages needed). Strings are written JSON-quoted, which is valid YAML."""
    pad = '  ' * ind
    if isinstance(v, dict):
        if not v: return '{}'
        return '\n'.join(f'{pad}{json.dumps(k)}:' + (f'\n{to_yaml(x, ind + 1)}' if isinstance(x, (dict, list)) and x else f' {to_yaml(x, 0)}') for k, x in v.items())
    if isinstance(v, list):
        if not v: return '[]'
        return '\n'.join(f'{pad}-' + (f'\n{to_yaml(x, ind + 1)}' if isinstance(x, (dict, list)) and x else f' {to_yaml(x, 0)}') for x in v)
    if v is None: return 'null'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return json.dumps(v)
    return json.dumps(v, ensure_ascii=False)

def load(name, src):
    if src.startswith('http'):
        req = urllib.request.Request(src, headers={'User-Agent': 'docs-import'})
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.loads(r.read())
    return json.loads(Path(src).read_text())

def main(args):
    srcs = dict(zip(SOURCES, args)) if args else SOURCES
    for name in SOURCES:
        spec = load(name, srcs.get(name, SOURCES[name]))
        dl = ROOT / 'api-spec' / 'downloads'
        dl.mkdir(exist_ok=True)
        (dl / f'{DOWNLOADS[name]}.json').write_text(json.dumps(spec, indent=2, ensure_ascii=False) + '\n')   # exact live document
        (dl / f'{DOWNLOADS[name]}.yaml').write_text(to_yaml(spec) + '\n')
        schemas = spec.get('components', {}).get('schemas', {})
        for s, schema, field, key, value in FIXES:
            if s != name: continue
            prop = schemas.get(schema, {}).get('properties', {}).get(field)
            if prop is None: print(f'  fix not applied: {schema}.{field} is no longer in the {name} spec'); continue
            if value is None: prop.pop(key, None)
            else: prop[key] = value
        out = ROOT / 'api-spec' / f'{name}.js'
        out.write_text(f'/* Generated by tools/import_spec.py from {SOURCES[name]}\n'
                       '   Do not edit by hand: run the script again (wording fixes go in FIXES in that script). */\n'
                       'window.SPECS = window.SPECS || {};\n'
                       f'window.SPECS.{name} = ' + json.dumps(spec, indent=1, ensure_ascii=False) + ';\n')
        n = sum(1 for p in spec['paths'].values() for m in p if m in ('get', 'post', 'put', 'patch', 'delete'))
        print(f'wrote {out.relative_to(ROOT)}: {n} endpoints')

if __name__ == '__main__':
    main(sys.argv[1:])
